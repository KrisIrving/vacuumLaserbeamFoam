import time

from generatePowderBed import (
    maximum_centerline_gap,
    percentile,
    piecewise_quantile_value,
    projected_coverage,
    target_volume_from_config,
    write_set_fields,
)

ROOT = Path(__file__).resolve().parents[2]
CASE = ROOT / "tutorials/vacuumLaserbeamFoam/M247_0p6Pa_track1500um6umV2"
CONFIG = CASE / "powderBedConfig.json"
CGS_TO_M = 0.01
N_BINS = 16
INSERTED_PARTICLES = 460
# Native 2026-10-12 21:38:35 pilot: smaller particles preferentially survived
# the 80 um top trim. These observed counts compensate the *numerical trim*,
# keeping the final number-based PSD tied to the user's experimental targets.
# Recheck after each native run; this is not a measured powder-flow property.
CALIBRATION_CONFIG_SHA256 = "0e3ca1caafe597d1406bde8ea5506169e7988747b636ec144df9fd17c5e18719"
CALIBRATION_ARCHIVE_SHA256 = "0a9d1e9bd446d2c7bab9f5ce46a86a4771936638849e5db0909e35e4762e3f83"
REFERENCE_RAW_COUNTS = (32, 33, 32, 36, 29, 35, 38, 25, 22, 29, 23, 26, 32, 40, 34, 34)
REFERENCE_FINAL_COUNTS = (28, 30, 25, 31, 21, 21, 23, 18, 17, 18, 15, 20, 17, 25, 20, 23)
BOUNDARY_TOLERANCE_M = 2e-8  # 0.02 um; soft-contact penetration, 0.3% of 6 um cell


def next_prime(value):
    while True:
        if value > 2 and all(value % divisor for divisor in range(2, math.isqrt(value) + 1)):
            return value
        value += 1


def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def create_input(work):
    work.mkdir(parents=True, exist_ok=True)
    (work / "post").mkdir(exist_ok=True)
    cfg = json.loads(CONFIG.read_text())
    if sha256(CONFIG) != CALIBRATION_CONFIG_SHA256:
        raise ValueError("Powder config changed; re-evaluate DEM trim calibration")
    bounds = cfg["footprint"]
    xmin, xmax = bounds["xMin"] / CGS_TO_M, bounds["xMax"] / CGS_TO_M
    zmin, zmax = bounds["zMin"] / CGS_TO_M, bounds["zMax"] / CGS_TO_M
    floor = cfg["substrateSurfaceY"] / CGS_TO_M
    top = (cfg["substrateSurfaceY"] + cfg["layerThickness"]) / CGS_TO_M
    diameters = [piecewise_quantile_value(cfg["diameterDistribution"], (i + 0.5) / N_BINS)
                 for i in range(N_BINS)]
    unscaled_weights = [d**3 * raw/final for d,raw,final in zip(
        diameters, REFERENCE_RAW_COUNTS, REFERENCE_FINAL_COUNTS)]
    weights = [weight/sum(unscaled_weights) for weight in unscaled_weights]
    seed_base = int(cfg["seed"])
    template_seeds = [next_prime(seed_base + 100 * i) for i in range(N_BINS)]
    distribution_seed = next_prime(seed_base + 2000)
    insertion_seed = next_prime(seed_base + 3000)
    # Existing laserbeamFoam DEM tutorial uses cgs, Hertz/history, and reduced
    # stiffness. These contact parameters are provisional, not M247 calibration.
    lines = [
        "# M247 DEM powder pilot; generated by tools/powderBed/m247_liggghts.py",
        "# Units: cgs. Output dump coordinates/radii are converted to SI by the audit.",
        "atom_style granular", "atom_modify map array", "boundary f f f", "newton off",
        "communicate single vel yes", "units cgs",
        f"region domain block {xmin:.12g} {xmax:.12g} {floor:.12g} 0.105 {zmin:.12g} {zmax:.12g} units box",
        "create_box 1 domain", "neighbor 0.0003 bin", "neigh_modify delay 0",
        "fix ym all property/global youngsModulus peratomtype 5e7",
        "fix pr all property/global poissonsRatio peratomtype 0.45",
        "fix re all property/global coefficientRestitution peratomtypepair 1 0.1",
        "fix fr all property/global coefficientFriction peratomtypepair 1 0.065",
        "pair_style gran model hertz tangential history", "pair_coeff * *",
        "fix integrate all nve/sphere", "timestep 0.00000005",
        "fix grav all gravity 981 vector 0 -1 0",
    ]
    for name, plane, pos in (("bed", "yplane", floor), ("left", "xplane", xmin),
                             ("right", "xplane", xmax), ("front", "zplane", zmin),
                             ("back", "zplane", zmax)):
        lines.append(f"fix {name} all wall/gran model hertz tangential history primitive type 1 {plane} {pos:.12g}")
    for i, d in enumerate(diameters):
        # 7950 kg/m3 is the solid density in the M247 CFD transportProperties.
        radius_cm = d / (2 * CGS_TO_M)
        lines.append(f"fix pt{i+1} all particletemplate/sphere {template_seeds[i]} atom_type 1 density constant 7.95 radius constant {radius_cm:.12g}")
    distribution = f"fix pdd all particledistribution/discrete {distribution_seed} {N_BINS} "
    distribution += " &\n    ".join(" ".join(f"pt{i+1} {weights[i]:.16g}" for i in range(j, min(j+4, N_BINS)))
                                  for j in range(0, N_BINS, 4))
    lines.append(distribution)
    lines.extend([
        f"region factory block {xmin+0.0041:.12g} {xmax-0.0041:.12g} 0.074 0.09 {zmin+0.0041:.12g} {zmax-0.0041:.12g} units box",
        f"fix ins all insert/rate/region seed {insertion_seed} distributiontemplate pdd &",
        f"    nparticles {INSERTED_PARTICLES} particlerate 50000 insert_every 1000 &",
        "    overlapcheck yes all_in yes vel constant 0 0 0 region factory ntry_mc 10000",
        "thermo 10000", "thermo_style custom step atoms ke cpu",
        "run 400000", "unfix ins",
        "write_dump all custom post/raw.dump id x y z radius vx vy vz modify sort id",
        "compute rad all property/atom radius",
        # Match the official LPBF_small DEM sequence: consume the per-atom
        # radius compute via a reduce/thermo output before evaluating the
        # height-selection variable between runs. A bare run 0 is insufficient.
        "compute radiusSum all reduce sum c_rad",
        "thermo_style custom step atoms c_radiusSum",
        "run 0",
        f'variable above atom "y+c_rad > {top:.12g}"',
        "group trim variable above", "delete_atoms group trim compress yes",
        # Official LPBF_small continues 250000 steps after height trimming.
        # The previous 50000-step relaxation left p95 speed above the gate.
        "run 250000",
        "write_dump all custom post/relaxed.dump id x y z radius vx vy vz modify sort id",
        "run 0",
        "group trimAfterRelax variable above", "delete_atoms group trimAfterRelax compress yes",
        "run 50000",
        "run 0",
        "group trimFinal variable above", "delete_atoms group trimFinal compress yes",
        "run 0",
        "write_dump all custom post/final.dump id x y z radius vx vy vz modify sort id",
    ])
    (work / "input.liggghts").write_text("\n".join(lines) + "\n")
    metadata = dict(schema=1,sourceConfig=str(CONFIG),sourceConfigSha256=sha256(CONFIG),
                    insertedParticlesRequested=INSERTED_PARTICLES,distributionBins=N_BINS,
                    liggghtsSeeds=dict(templates=template_seeds,distribution=distribution_seed,
                                       insertion=insertion_seed),
                    distributionBasis="experimental number-quantile bins; LIGGGHTS mass weights compensated for observed 80 um trim survival",
                    trimCalibration=dict(referenceArchiveSha256=CALIBRATION_ARCHIVE_SHA256,
                                         referenceRawCounts=REFERENCE_RAW_COUNTS,
                                         referenceFinalCounts=REFERENCE_FINAL_COUNTS,
                                         massWeights=weights),
                    contactParameters="provisional upstream laserbeamFoam DEM tutorial values; M247 solid density 7.95 g/cm3",
                    cgsToMeters=CGS_TO_M)
    (work / "demInput.json").write_text(json.dumps(metadata, indent=2) + "\n")


def read_dump(path):
    lines = path.read_text().splitlines()
    try:
        atom_line = next(i for i, s in enumerate(lines) if s.startswith("ITEM: ATOMS "))
        n_line = lines.index("ITEM: NUMBER OF ATOMS")
    except (StopIteration, ValueError) as error:
        raise ValueError(f"Invalid LIGGGHTS dump header: {path}") from error
    count = int(lines[n_line + 1])
    columns = lines[atom_line].split()[2:]
    required = ("id", "x", "y", "z", "radius", "vx", "vy", "vz")
    if not all(key in columns for key in required):
        raise ValueError(f"Missing LIGGGHTS dump columns in {path}: {columns}")
    atoms = []
    for line in lines[atom_line + 1:]:
        if line.startswith("ITEM:"):
            break
        values = line.split()
        if len(values) != len(columns):
            raise ValueError(f"Malformed particle row in {path}")
        row = {key: float(values[columns.index(key)]) for key in required if key != "id"}
        row["id"] = int(values[columns.index("id")])
        if not all(math.isfinite(value) for value in row.values()) or row["radius"] <= 0:
            raise ValueError(f"Non-finite or invalid particle in {path}")
        atoms.append(row)
    if len(atoms) != count or len({a["id"] for a in atoms}) != count:
        raise ValueError(f"Particle count or IDs do not match dump header: {path}")
    return sorted(atoms, key=lambda atom: atom["id"])


def volume_weighted_percentile(diameters, fraction):
    """Return a volume-cumulative diameter without assuming a measurement basis."""
    values = sorted(diameters)
    total = sum(d**3 for d in values)
    cumulative = 0.0
    for d in values:
        cumulative += d**3
        if cumulative >= fraction*total:
            return d
    return values[-1]


def audit(work):
    cfg = json.loads(CONFIG.read_text())
    meta = json.loads((work / "demInput.json").read_text())
    if sha256(CONFIG) != meta["sourceConfigSha256"]:
        raise ValueError("M247 powder configuration changed after DEM input generation")
    raw, final = read_dump(work / "post/raw.dump"), read_dump(work / "post/final.dump")
    if not final:
        raise ValueError("No DEM particles remain after 80 um layer trim")
    particles = [dict(x=a["x"]*CGS_TO_M, y=a["y"]*CGS_TO_M,
                      z=a["z"]*CGS_TO_M, r=a["radius"]*CGS_TO_M) for a in final]
    bounds = cfg["footprint"]
    floor = cfg["substrateSurfaceY"]
    ceiling = floor + cfg["layerThickness"]
    penetrations = {face: 0.0 for face in ("xMin", "xMax", "zMin", "zMax", "floor", "top")}
    penetration_counts = {face: 0 for face in penetrations}
    for p in particles:
        face_depths = dict(xMin=bounds["xMin"]-(p["x"]-p["r"]),
                           xMax=p["x"]+p["r"]-bounds["xMax"],
                           zMin=bounds["zMin"]-(p["z"]-p["r"]),
                           zMax=p["z"]+p["r"]-bounds["zMax"],
                           floor=floor-(p["y"]-p["r"]),
                           top=p["y"]+p["r"]-ceiling)
        for face, depth in face_depths.items():
            if depth > 0:
                penetrations[face] = max(penetrations[face], depth)
                penetration_counts[face] += 1
    if max(penetrations.values()) > BOUNDARY_TOLERANCE_M:
        raise ValueError(f"DEM boundary penetration exceeds {BOUNDARY_TOLERANCE_M*1e6:.3f} um: "
                         f"{ {face: round(depth*1e6, 6) for face, depth in penetrations.items()} }")
    min_gap = float("inf")
    for i, a in enumerate(particles):
        for b in particles[i+1:]:
            distance = math.sqrt((a["x"]-b["x"])**2 + (a["y"]-b["y"])**2 + (a["z"]-b["z"])**2)
            min_gap = min(min_gap, distance-a["r"]-b["r"])
    area = (bounds["xMax"]-bounds["xMin"])*(bounds["zMax"]-bounds["zMin"])
    target, nominal, packing_target = target_volume_from_config(cfg, area, cfg["layerThickness"])
    volume = sum(4*math.pi*p["r"]**3/3 for p in particles)
    ds = [2*p["r"] for p in particles]
    spacing = cfg["coverage"]["gridSpacing"]
    corridor = cfg["coverage"]["corridor"]
    lower_surface = [p["y"]-p["r"]-floor for p in particles]
    mean_d = sum(ds)/len(ds)
    mean_h = sum(lower_surface)/len(lower_surface)
    cov = sum((d-mean_d)*(h-mean_h) for d,h in zip(ds,lower_surface))
    var_d = sum((d-mean_d)**2 for d in ds)
    var_h = sum((h-mean_h)**2 for h in lower_surface)
    size_height_corr = cov/math.sqrt(var_d*var_h) if var_d*var_h else 0.0
    segment_coverage=[]
    for i in range(5):
        x0=corridor["xMin"]+(corridor["xMax"]-corridor["xMin"])*i/5
        x1=corridor["xMin"]+(corridor["xMax"]-corridor["xMin"])*(i+1)/5
        segment_coverage.append(dict(xMin_m=x0,xMax_m=x1,
                                     coverage=projected_coverage(particles,
                                         dict(xMin=x0,xMax=x1,zMin=corridor["zMin"],zMax=corridor["zMax"]),
                                         spacing)))
    velocity = [math.sqrt(a["vx"]**2+a["vy"]**2+a["vz"]**2)*CGS_TO_M for a in final]
    rank = sorted(range(len(velocity)), key=lambda i: velocity[i])
    p95_velocity = velocity[rank[min(len(rank)-1, int(.95*(len(rank)-1)))]]
    manifest = dict(generator="LIGGGHTS-PUBLIC-DEM", seed=cfg["seed"],
                    liggghtsSeeds=meta["liggghtsSeeds"],
                    rawDumpSha256=sha256(work / "post/raw.dump"),
                    finalDumpSha256=sha256(work / "post/final.dump"),
                    particleCount=len(particles),rawParticleCount=len(raw),
                    trimmedParticleCount=len(raw)-len(final),
                    substrateSurfaceY_m=floor,layerThickness_m=cfg["layerThickness"],
                    nominalLayerThickness_m=nominal,targetPackingFractionNominalLayer=packing_target,
                    targetSolidVolume_m3=target,solidVolume_m3=volume,
                    actualPackingFractionNominalLayer=volume/(area*nominal),
                    actualSolidFractionGeometricEnvelope=volume/(area*cfg["layerThickness"]),
                    equivalentDenseThickness_m=volume/area,
                    diameterMin_m=min(ds),diameterD10_m=percentile(ds,.1),
                    diameterD50_m=percentile(ds,.5),diameterD90_m=percentile(ds,.9),
                    diameterVolumeD10_m=volume_weighted_percentile(ds,.1),
                    diameterVolumeD50_m=volume_weighted_percentile(ds,.5),
                    diameterVolumeD90_m=volume_weighted_percentile(ds,.9),
                    experimentalPsdBasis="unconfirmed; numerical gate uses number count",
                    diameterMax_m=max(ds),minimumInterparticleGap_m=min_gap,
                    highestParticleTop_m=max(p["y"]+p["r"] for p in particles),
                    boundaryPenetrationMax_m=penetrations,
                    boundaryPenetrationCounts=penetration_counts,
                    boundaryPenetrationTolerance_m=BOUNDARY_TOLERANCE_M,
                    projectedCoverageFractionFootprint=projected_coverage(particles,bounds,spacing),
                    projectedCoverageFractionCorridor=projected_coverage(particles,corridor,spacing),
                    maximumUncoveredCenterlineGap_m=maximum_centerline_gap(
                        particles,corridor["xMin"],corridor["xMax"],cfg["coverage"]["centerlineZ"],spacing),
                    corridorCoverageBy300um=segment_coverage,
                    diameterVsLowerSurfacePearson=size_height_corr,
                    largeParticleSubstrateContactFraction=(
                        sum(h<=1e-6 for d,h in zip(ds,lower_surface) if d>=60e-6)
                        /max(1,sum(d>=60e-6 for d in ds))),
                    smallParticleSubstrateContactFraction=(
                        sum(h<=1e-6 for d,h in zip(ds,lower_surface) if d<40e-6)
                        /max(1,sum(d<40e-6 for d in ds))),
                    velocityP95_m_per_s=p95_velocity,config=cfg)
    # Gates protect the next stage; clipping can bias the PSD, so a successful
    # LIGGGHTS exit alone never means the bed is acceptable.
    gates = dict(particleCount=len(particles)>0,
                 boundary=max(penetrations.values())<=BOUNDARY_TOLERANCE_M,
                 d10=abs(manifest["diameterD10_m"]/36.5e-6-1)<=.10,
                 d50=abs(manifest["diameterD50_m"]/52.6e-6-1)<=.05,
                 d90=abs(manifest["diameterD90_m"]/74.4e-6-1)<=.10,
                 packing=abs(manifest["actualPackingFractionNominalLayer"]-.58)<=.03,
                 overlap=min_gap>=-0.5e-6,
                 settled=p95_velocity<=.005)
    manifest["preflightGates"] = gates
    manifest["preflightAdvisoryKeys"] = ["packing"]
    # Nominal-layer packing is a reported comparison with a provisional target,
    # not an experimental acceptance criterion. Keep its flag for provenance.
    manifest["readyForReview"] = all(value for key, value in gates.items() if key != "packing")
    manifest["productionApproved"] = False
    (work / "powderManifest.json").write_text(json.dumps(manifest,indent=2)+"\n")
    with (work / "powderParticles.csv").open("w",newline="") as stream:
        writer=csv.writer(stream)
        writer.writerow(("id","x_m","y_m","z_m","radius_m","diameter_m"))
        for atom,p in zip(final,particles):
            writer.writerow((atom["id"],f'{p["x"]:.12g}',f'{p["y"]:.12g}',
                             f'{p["z"]:.12g}',f'{p["r"]:.12g}',f'{2*p["r"]:.12g}'))
    write_set_fields(work / "setFieldsDict",particles,floor)
    print(json.dumps({"particleCount":len(final),"packingNominal":manifest["actualPackingFractionNominalLayer"],
                      "numberD10_D50_D90_um":[1e6*manifest[f"diameterD{q}_m"] for q in (10,50,90)],
                      "volumeD10_D50_D90_um":[1e6*manifest[f"diameterVolumeD{q}_m"] for q in (10,50,90)],
                      "corridorCoverage":manifest["projectedCoverageFractionCorridor"],
                      "gates":gates,"readyForReview":manifest["readyForReview"]},indent=2),flush=True)


def package(work, exit_code):
    names=("input.liggghts","demInput.json","log.liggghts","run.json",
           "post/raw.dump","post/final.dump","powderManifest.json",
           "powderParticles.csv","setFieldsDict")
    optional=("failure.json","post/relaxed.dump")
    missing=[name for name in names if not (work/name).is_file()]
    summary=dict(schema=1,exitCode=exit_code,missingFiles=missing,
                 files={name:sha256(work/name) for name in names+optional
                        if (work/name).is_file()})
    (work/"reviewManifest.json").write_text(json.dumps(summary,indent=2)+"\n")
    archive=work.parent/("M247_"+work.name+"_review.tar.gz")
    with tarfile.open(archive,"w:gz") as tar:
        for name in names+optional+("reviewManifest.json",):
            if (work/name).is_file():tar.add(work/name,arcname=work.name+"/"+name)
    print(f"Review archive: {archive}\nSend this single archive, including on failure. No CFD advanced.",flush=True)


def verify_template():
    path = CASE / "constant/powderManifest.json"
    manifest = json.loads(path.read_text())
    if (manifest.get("generator") != "LIGGGHTS-PUBLIC-DEM"
            or not manifest.get("readyForReview")
            or not all(value for key, value in manifest.get("preflightGates", {}).items()
                       if key != "packing")
            or not manifest.get("finalDumpSha256")):
        raise ValueError("V2 still has provisional geometric powder or unreviewed DEM powder; no CFD may start")


def resolve_liggghts():
    """Resolve a real executable; shell aliases are invisible to Python."""
    override = os.environ.get("LIGGGHTS_EXECUTABLE")
    if override:
        path = Path(override).expanduser()
        if not path.is_file() or not os.access(path, os.X_OK):
            raise FileNotFoundError(f"LIGGGHTS_EXECUTABLE is not an executable file: {path}")
        return path.resolve()
    candidates = (Path.home() / "CFDEM/LIGGGHTS/src-build/liggghts",
                  Path(shutil.which("liggghts")) if shutil.which("liggghts") else None)
    for path in candidates:
        if path is not None and path.is_file() and os.access(path, os.X_OK):
            return path.resolve()
    raise FileNotFoundError(
        "LIGGGHTS executable not found; set LIGGGHTS_EXECUTABLE to the absolute "
        "path (a shell alias is not available to Python)")


def run_native(work):
    create_input(work)
    executable = resolve_liggghts()
    start = time.perf_counter()
    # Official DEM_small/Allrun pattern: liggghts < input.liggghts &> log.liggghts.
    # Pass the verified executable as a positional parameter, never shell text.
    command = ["bash", "-c", 'exec "$1" < input.liggghts > log.liggghts 2>&1',
               "m247-liggghts", str(executable)]
    result = subprocess.run(command, cwd=work, check=False)
    report = dict(executable=str(Path(executable).resolve()),
                  executableSha256=sha256(Path(executable)),
                  command=command,
                  returncode=result.returncode,elapsedWallSeconds=time.perf_counter()-start)
    (work / "run.json").write_text(json.dumps(report, indent=2) + "\n")
    if result.returncode:
        raise RuntimeError(f"LIGGGHTS failed with return code {result.returncode}; inspect log.liggghts")
    audit(work)


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action",choices=("prepare","audit","package","run","verify-template"))
    parser.add_argument("--work",type=Path)
    parser.add_argument("--exit-code",type=int,default=0)
    args=parser.parse_args()
    if args.action=="verify-template":
        try:
            verify_template()
        except ValueError as error:
            print(error,flush=True)
            raise SystemExit(2)
    else:
        if args.work is None:
            parser.error("--work is required")
        if args.action=="prepare":create_input(args.work)
        elif args.action=="audit":audit(args.work)
        elif args.action=="package":package(args.work,args.exit_code)
        else:
            code=0
            try:
                run_native(args.work)
            except Exception as error:
                code=1
                args.work.mkdir(parents=True,exist_ok=True)
                (args.work/"failure.json").write_text(json.dumps(
                    {"schema":1,"errorType":type(error).__name__,"message":str(error)},
                    indent=2)+"\n")
                print(f"DEM preflight failed: {error}",flush=True)
            finally:
                package(args.work,code)
            if code:
                raise SystemExit(code)

