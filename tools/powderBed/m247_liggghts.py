#!/usr/bin/env python3
"""Prepare and audit a LIGGGHTS powder bed for the M247 1.5 mm case.

This tool never edits the CFD template. A native DEM run must be reviewed before
its particle CSV and setFieldsDict can replace the provisional geometric bed.
"""
